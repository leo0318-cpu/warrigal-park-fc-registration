"""The member register: validation, creation, search, update and deactivation (WBS 4.1).

Scope is the member entity only. Guardians and the member/guardian link (WBS 4.2), season
registrations (WBS 4.3) and team rosters (WBS 4.4) belong to other work packages: this
module never writes their tables, only exposes the member state they need.

Four decisions from `docs/dev/4.1-member-crud-design.md` shape everything here:

1. **Search must not collapse people who share a name.** Search returns every match and the
   registrar disambiguates by date of birth, never by name alone.
2. **Members are deactivated, never deleted** (Decision Log D-06): the row stays queryable.
3. **Every required field is validated before persistence**, and one error message names
   every field that is missing rather than failing one field at a time.
4. **Persistence is deliberately boring** — SQLite through the standard library.

Nothing in this module prints: each operation returns a result object, and `__main__.py`
decides how to show it. That keeps the rules testable without a terminal.
"""

from __future__ import annotations

import os
import sqlite3
from dataclasses import dataclass
from datetime import date, datetime
from typing import Any, Mapping, Sequence

from warrigal.db import connect

__all__ = [
    "ADULT_AGE_DEFAULT",
    "Member",
    "OperationResult",
    "adult_age",
    "age_at",
    "blank_to_none",
    "can_be_placed_on_roster",
    "create_member",
    "find_by_family_name",
    "get_member",
    "is_senior",
    "member_from_row",
    "normalise_date_of_birth",
    "parse_date_of_birth",
    "requires_linked_guardian",
    "set_active",
    "update_member",
]

#: Age at which a member may be registered without a linked guardian
#: (`WARRIGAL_ADULT_AGE`, documented default 18).
ADULT_AGE_DEFAULT = 18

#: Fields a registrar may edit. `member_id` is system-generated and is never in this list.
EDITABLE_FIELDS = ("given_name", "family_name", "date_of_birth", "contact_number")

#: Date formats accepted for a date of birth. ISO first because that is how the value is
#: stored; day-before-month second because that is how the club writes dates on paper.
DOB_FORMATS = ("%Y-%m-%d", "%d/%m/%Y")

_LIST_COLUMNS = (
    "member_id, given_name, family_name, date_of_birth, contact_number, "
    "is_active, created_at, updated_at"
)


# --- Values -----------------------------------------------------------------------------


@dataclass(frozen=True)
class Member:
    """A row of the member register.

    `member_id` is generated by the system and never supplied by a user. `is_active` is the
    deactivation flag of Decision Log D-06 — there is no deleted state.
    """

    member_id: int
    given_name: str
    family_name: str
    date_of_birth: date
    contact_number: str | None = None
    is_active: bool = True
    created_at: str = ""
    updated_at: str = ""

    @property
    def full_name(self) -> str:
        """Return the name as the club writes it, given name first."""
        return f"{self.given_name} {self.family_name}"

    def age_at(self, on: date) -> int:
        """Return this member's age on a given date."""
        return age_at(self.date_of_birth, on)

    def is_minor_at(self, on: date, *, adult_age: int | None = None) -> bool:
        """Return whether this member still needs a linked guardian on that date."""
        return not is_senior(self.date_of_birth, on, adult_age=adult_age)


@dataclass(frozen=True)
class OperationResult:
    """The outcome of one register operation.

    `errors` are reasons the operation was refused; `warnings` are things the registrar
    should know but which did not stop the work — a suspected duplicate, for instance.
    `requires_confirmation` marks the case where nothing was written and the caller must
    repeat the call with `confirm_duplicate=True`.
    """

    success: bool
    message: str = ""
    member: Member | None = None
    members: tuple[Member, ...] = ()
    errors: tuple[str, ...] = ()
    warnings: tuple[str, ...] = ()
    requires_confirmation: bool = False
    changed: bool = False

    @property
    def ok(self) -> bool:
        """Alias for `success`, so callers can read `if result.ok:`."""
        return self.success

    @property
    def has_warnings(self) -> bool:
        """Return whether the registrar should read something before trusting the result."""
        return bool(self.warnings)


def member_from_row(row: sqlite3.Row | Mapping[str, Any]) -> Member:
    """Build a `Member` from a database row, tolerating a row without the audit columns."""
    keys = set(row.keys())
    return Member(
        member_id=int(row["member_id"]),
        given_name=str(row["given_name"]),
        family_name=str(row["family_name"]),
        date_of_birth=date.fromisoformat(str(row["date_of_birth"])),
        contact_number=row["contact_number"] if "contact_number" in keys else None,
        is_active=bool(row["is_active"]) if "is_active" in keys else True,
        created_at=str(row["created_at"]) if "created_at" in keys else "",
        updated_at=str(row["updated_at"]) if "updated_at" in keys else "",
    )


# --- Business rules ---------------------------------------------------------------------


def adult_age() -> int:
    """Return the age at which a member no longer needs a linked guardian.

    `WARRIGAL_ADULT_AGE` (documented default 18). An unreadable value falls back to the
    default rather than stopping the application.
    """
    raw = os.environ.get("WARRIGAL_ADULT_AGE", "").strip()
    if not raw:
        return ADULT_AGE_DEFAULT
    try:
        return int(raw)
    except ValueError:
        return ADULT_AGE_DEFAULT


def age_at(date_of_birth: date, on: date) -> int:
    """Return the completed age on a date, counting a birthday falling on that date."""
    return on.year - date_of_birth.year - ((on.month, on.day) < (date_of_birth.month, date_of_birth.day))


def is_senior(date_of_birth: date, on: date, *, adult_age: int | None = None) -> bool:
    """Return whether a member counts as an adult on a given date.

    The boundary case matters: a player whose eighteenth birthday falls *on* the season
    start is an adult, because `age_at` counts the birthday. A player whose birthday falls
    one day later is still a minor (CONTRIBUTING example `fix(4.3): treat 18th birthday on
    season start as adult`).
    """
    limit = ADULT_AGE_DEFAULT if adult_age is None else adult_age
    return age_at(date_of_birth, on) >= limit


def requires_linked_guardian(
    date_of_birth: date, *, season_start: date, adult_age: int | None = None
) -> bool:
    """Return whether this member needs a linked guardian for the season.

    This is the member-side half of the one rule that must never break — a player under 18
    cannot complete a registration without a linked guardian. The member register reports
    the requirement; refusing an incomplete registration is WBS 4.3's job, and the roster
    check exposed here is `can_be_placed_on_roster`.
    """
    return not is_senior(date_of_birth, season_start, adult_age=adult_age)


# --- Validation -------------------------------------------------------------------------


def blank_to_none(value: str | None) -> str | None:
    """Return a stripped value, or `None` when it is empty or whitespace."""
    if value is None:
        return None
    stripped = value.strip()
    return stripped or None


def parse_date_of_birth(value: str | None) -> tuple[date | None, str | None]:
    """Parse a date of birth, returning `(date, error)`.

    Accepts `YYYY-MM-DD` and the day-first `DD/MM/YYYY` the club writes on paper forms. The
    two failure modes are reported separately because they mean different things to a
    registrar: a date that does not exist (`2025-02-30`) is a keying mistake, a date in the
    future is a mis-typed year.
    """
    raw = blank_to_none(value)
    if raw is None:
        return None, "date_of_birth is required"

    parsed: date | None = None
    for pattern in DOB_FORMATS:
        try:
            parsed = datetime.strptime(raw, pattern).date()
        except ValueError:
            continue
        break

    if parsed is None:
        return None, (
            f"date_of_birth '{raw}' is not a real calendar date "
            "(use YYYY-MM-DD or DD/MM/YYYY)"
        )
    if parsed > date.today():
        return None, f"date_of_birth '{parsed.isoformat()}' is in the future"
    return parsed, None


def normalise_date_of_birth(value: str | date | None) -> tuple[str | None, str | None]:
    """Return a date of birth as stored ISO text, with `(value, error)`."""
    if isinstance(value, date):
        if value > date.today():
            return None, f"date_of_birth '{value.isoformat()}' is in the future"
        return value.isoformat(), None
    parsed, error = parse_date_of_birth(value)
    return (parsed.isoformat() if parsed else None), error


def _collect_validation_errors(
    *, given_name: str | None, family_name: str | None, date_of_birth: str | date | None
) -> tuple[list[str], dict[str, Any]]:
    """Validate every required field at once, returning the errors and the clean values."""
    errors: list[str] = []
    clean: dict[str, Any] = {}

    clean_given = blank_to_none(given_name)
    if clean_given is None:
        errors.append("given_name is required")
    clean["given_name"] = clean_given

    clean_family = blank_to_none(family_name)
    if clean_family is None:
        errors.append("family_name is required")
    clean["family_name"] = clean_family

    iso_dob, dob_error = normalise_date_of_birth(date_of_birth)
    if dob_error:
        errors.append(dob_error)
    clean["date_of_birth"] = iso_dob

    return errors, clean


def _format_errors(errors: Sequence[str]) -> str:
    """Join validation errors into one message, naming every field that failed.

    US-01 acceptance criterion 4: the registrar is told about all missing fields in a single
    round trip, not one field per attempt.
    """
    if len(errors) == 1:
        return f"Cannot save the member: {errors[0]}."
    listed = "; ".join(errors)
    return f"Cannot save the member — {len(errors)} problems, nothing was saved: {listed}."


# --- Persistence helpers ----------------------------------------------------------------


def _fetch_member(connection: sqlite3.Connection, member_id: int) -> Member | None:
    row = connection.execute(
        f"SELECT {_LIST_COLUMNS} FROM members WHERE member_id = ?", (member_id,)
    ).fetchone()
    return member_from_row(row) if row is not None else None


def _find_active_same_person(
    connection: sqlite3.Connection,
    *,
    given_name: str,
    family_name: str,
    date_of_birth: str,
    exclude_member_id: int | None = None,
) -> Member | None:
    """Return an existing **active** member with the same name and date of birth, if any.

    The comparison is case-insensitive and ignores surrounding whitespace so that
    `  nguyen ` and `Nguyen` are treated as the same person. Only active members count:
    a deactivated record is history, not a duplicate (D-06).
    """
    sql = (
        f"SELECT {_LIST_COLUMNS} FROM members "
        "WHERE is_active = 1 "
        "  AND lower(trim(given_name)) = lower(trim(?)) "
        "  AND lower(trim(family_name)) = lower(trim(?)) "
        "  AND date_of_birth = ?"
    )
    params: list[Any] = [given_name, family_name, date_of_birth]
    if exclude_member_id is not None:
        sql += " AND member_id <> ?"
        params.append(exclude_member_id)
    sql += " ORDER BY member_id LIMIT 1"
    row = connection.execute(sql, params).fetchone()
    return member_from_row(row) if row is not None else None


def _duplicate_warning(candidate: Member) -> str:
    """Word the duplicate warning so the registrar knows what to check next."""
    return (
        f"Possible duplicate: an active member already has this name and date of birth "
        f"(member_id {candidate.member_id}, {candidate.full_name}, "
        f"born {candidate.date_of_birth.isoformat()}). "
        "Check the date of birth before saving — people who share a name are separate "
        "members. Nothing has been saved yet; repeat with --confirm-duplicate to save anyway."
    )


def _insert_member(
    connection: sqlite3.Connection,
    *,
    given_name: str,
    family_name: str,
    date_of_birth: str,
    contact_number: str | None,
) -> int:
    """Insert the member and return the system-generated identifier."""
    cursor = connection.execute(
        "INSERT INTO members (given_name, family_name, date_of_birth, contact_number) "
        "VALUES (?, ?, ?, ?)",
        (given_name, family_name, date_of_birth, contact_number),
    )
    return int(cursor.lastrowid or 0)


# --- US-01 Create -----------------------------------------------------------------------


def create_member(
    *,
    given_name: str | None,
    family_name: str | None,
    date_of_birth: str | date | None,
    contact_number: str | None = None,
    confirm_duplicate: bool = False,
    connection: sqlite3.Connection | None = None,
) -> OperationResult:
    """Create a member, validating every required field before anything is written.

    Required: given name, family name, date of birth. The date must be a real calendar date
    and not in the future. The identifier is generated by the system.

    When an **active** member already has the same name and date of birth, the registrar
    gets a warning and nothing is saved until the call is repeated with
    `confirm_duplicate=True` — US-01 acceptance criterion 5 requires the warning to come
    *before* saving, and only the person at the desk can tell two same-named players apart.
    """
    errors, clean = _collect_validation_errors(
        given_name=given_name, family_name=family_name, date_of_birth=date_of_birth
    )
    if errors:
        return OperationResult(
            success=False, message=_format_errors(errors), errors=tuple(errors)
        )

    contact = blank_to_none(contact_number)

    def _work(connection: sqlite3.Connection) -> OperationResult:
        duplicate = _find_active_same_person(
            connection,
            given_name=clean["given_name"],
            family_name=clean["family_name"],
            date_of_birth=clean["date_of_birth"],
        )
        if duplicate is not None and not confirm_duplicate:
            return OperationResult(
                success=False,
                message=_duplicate_warning(duplicate),
                requires_confirmation=True,
            )

        try:
            member_id = _insert_member(
                connection,
                given_name=clean["given_name"],
                family_name=clean["family_name"],
                date_of_birth=clean["date_of_birth"],
                contact_number=contact,
            )
        except sqlite3.IntegrityError as exc:  # pragma: no cover - defensive
            return OperationResult(
                success=False,
                message=f"Cannot save the member: the database refused the record ({exc}).",
                errors=(str(exc),),
            )

        created = _fetch_member(connection, member_id)
        warnings = (_duplicate_warning(duplicate),) if duplicate is not None else ()
        return OperationResult(
            success=True,
            message=(
                f"Saved member {member_id}, {created.full_name if created else clean['given_name']}"
                f" (born {clean['date_of_birth']})."
            ),
            member=created,
            warnings=warnings,
            changed=True,
        )

    if connection is not None:
        return _work(connection)
    with connect() as owned:
        return _work(owned)


# --- US-02 Find -------------------------------------------------------------------------


def find_by_family_name(
    family_name: str,
    *,
    include_inactive: bool = False,
    connection: sqlite3.Connection | None = None,
) -> OperationResult:
    """Return every member whose family name contains `family_name`, case-insensitively.

    All matches are returned, each carrying its own date of birth: two players called
    Nguyen are two rows, never one (US-01 acceptance criterion 2). Deactivated members are
    excluded unless `include_inactive=True` (US-04). No match is an explicit empty result,
    not an error.
    """
    needle = blank_to_none(family_name)
    if needle is None:
        errors = ("family_name is required",)
        return OperationResult(
            success=False,
            message="Cannot search — " + "; ".join(errors) + ".",
            errors=errors,
        )

    def _work(connection: sqlite3.Connection) -> OperationResult:
        like = f"%{needle.lower()}%"
        sql = (
            f"SELECT {_LIST_COLUMNS} FROM members "
            "WHERE lower(family_name) LIKE ? ESCAPE '\\' "
        )
        if not include_inactive:
            sql += "AND is_active = 1 "
        sql += "ORDER BY family_name COLLATE NOCASE, given_name COLLATE NOCASE, date_of_birth"
        rows = connection.execute(sql, (like,)).fetchall()
        members = tuple(member_from_row(row) for row in rows)
        if not members:
            message = (
                f"No members match family name '{needle}'"
                + ("" if include_inactive else " (active members only)")
                + ". That is an empty result, not an error."
            )
            warnings: tuple[str, ...] = ()
        else:
            message = f"{len(members)} member(s) match family name '{needle}'."
            warnings = (
                ("Both active and deactivated members are shown." if include_inactive else ""),
            ) if include_inactive else ()
        return OperationResult(
            success=True,
            message=message,
            members=members,
            warnings=warnings,
        )

    if connection is not None:
        return _work(connection)
    with connect() as owned:
        return _work(owned)


def get_member(
    member_id: int, *, connection: sqlite3.Connection | None = None
) -> OperationResult:
    """Return one member by identifier, active or deactivated.

    A deactivated member stays retrievable: registration history must survive for insurance
    and audit purposes (Decision Log D-06).
    """

    def _work(connection: sqlite3.Connection) -> OperationResult:
        if not _is_identifier(member_id):
            return OperationResult(
                success=False,
                message=f"'{member_id}' is not a valid member id.",
                errors=("member_id must be a whole number",),
            )
        member = _fetch_member(connection, member_id)
        if member is None:
            return OperationResult(
                success=False,
                message=f"No member with member_id {member_id}.",
                errors=("unknown member_id",),
            )
        state = "active" if member.is_active else "deactivated"
        return OperationResult(
            success=True,
            message=(
                f"Member {member.member_id}, {member.full_name}, born "
                f"{member.date_of_birth.isoformat()} ({state})."
            ),
            member=member,
        )

    if connection is not None:
        return _work(connection)
    with connect() as owned:
        return _work(owned)


# --- US-03 Update -----------------------------------------------------------------------


def update_member(
    member_id: int,
    *,
    given_name: str | None = None,
    family_name: str | None = None,
    date_of_birth: str | date | None = None,
    contact_number: str | None = None,
    clear_contact_number: bool = False,
    confirm_duplicate: bool = False,
    connection: sqlite3.Connection | None = None,
) -> OperationResult:
    """Change any editable field of an existing member and persist it.

    Only the fields passed are touched; a field left as `None` keeps its stored value, and
    `clear_contact_number=True` removes the contact number. Validation is the same as for
    creation: the date of birth must be a real, non-future date, and all problems are
    reported at once. The identifier never changes.

    An unknown identifier is an error and nothing is written.
    """

    def _work(connection: sqlite3.Connection) -> OperationResult:
        if not _is_identifier(member_id):
            return OperationResult(
                success=False,
                message=f"'{member_id}' is not a valid member id.",
                errors=("member_id must be a whole number",),
            )

        current = _fetch_member(connection, member_id)
        if current is None:
            return OperationResult(
                success=False,
                message=f"Cannot update: no member with member_id {member_id}.",
                errors=("unknown member_id",),
            )

        errors: list[str] = []
        updates: dict[str, Any] = {}

        if given_name is not None:
            clean_given = blank_to_none(given_name)
            if clean_given is None:
                errors.append("given_name is required")
            updates["given_name"] = clean_given

        if family_name is not None:
            clean_family = blank_to_none(family_name)
            if clean_family is None:
                errors.append("family_name is required")
            updates["family_name"] = clean_family

        if date_of_birth is not None:
            iso_dob, dob_error = normalise_date_of_birth(date_of_birth)
            if dob_error:
                errors.append(dob_error)
            updates["date_of_birth"] = iso_dob

        if clear_contact_number:
            updates["contact_number"] = None
        elif contact_number is not None:
            updates["contact_number"] = blank_to_none(contact_number)

        if errors:
            return OperationResult(
                success=False, message=_format_errors(errors), errors=tuple(errors)
            )

        if not updates:
            return OperationResult(
                success=True,
                message=f"Nothing to update on member {member_id}.",
                member=current,
            )

        prospective = {
            "given_name": updates.get("given_name", current.given_name),
            "family_name": updates.get("family_name", current.family_name),
            "date_of_birth": updates.get("date_of_birth", current.date_of_birth.isoformat()),
        }
        duplicate = _find_active_same_person(
            connection,
            given_name=prospective["given_name"],
            family_name=prospective["family_name"],
            date_of_birth=prospective["date_of_birth"],
            exclude_member_id=member_id,
        )
        if duplicate is not None and not confirm_duplicate:
            return OperationResult(
                success=False,
                message=_duplicate_warning(duplicate),
                member=current,
                requires_confirmation=True,
            )

        assignments = ", ".join(f"{field} = ?" for field in updates)
        params: list[Any] = list(updates.values())
        params.append(member_id)
        connection.execute(
            f"UPDATE members SET {assignments}, updated_at = datetime('now') "
            "WHERE member_id = ?",
            params,
        )

        updated = _fetch_member(connection, member_id)
        changed_fields = ", ".join(sorted(updates))
        warnings = (_duplicate_warning(duplicate),) if duplicate is not None else ()
        return OperationResult(
            success=True,
            message=(
                f"Updated member {member_id} ({changed_fields}). "
                f"The id is unchanged: {member_id}."
            ),
            member=updated,
            warnings=warnings,
            changed=True,
        )

    if connection is not None:
        return _work(connection)
    with connect() as owned:
        return _work(owned)


# --- US-04 Deactivate / reactivate ------------------------------------------------------


def set_active(
    member_id: int,
    active: bool,
    *,
    connection: sqlite3.Connection | None = None,
) -> OperationResult:
    """Deactivate or reactivate a member, keeping the record and its history.

    Deactivation is deliberately reversible and never destructive: the row, its identifier
    and everything referring to it survive (D-06). Repeating the call is not an error — a
    deactivated member stays deactivated.
    """

    def _work(connection: sqlite3.Connection) -> OperationResult:
        if not _is_identifier(member_id):
            return OperationResult(
                success=False,
                message=f"'{member_id}' is not a valid member id.",
                errors=("member_id must be a whole number",),
            )

        current = _fetch_member(connection, member_id)
        if current is None:
            verb = "reactivate" if active else "deactivate"
            return OperationResult(
                success=False,
                message=f"Cannot {verb}: no member with member_id {member_id}.",
                errors=("unknown member_id",),
            )

        verb = "reactivate" if active else "deactivate"
        if current.is_active == active:
            state = "already active" if active else "already deactivated"
            return OperationResult(
                success=True,
                message=f"Member {member_id} is {state}; nothing changed.",
                member=current,
            )

        connection.execute(
            "UPDATE members SET is_active = ?, updated_at = datetime('now') "
            "WHERE member_id = ?",
            (1 if active else 0, member_id),
        )
        updated = _fetch_member(connection, member_id)
        if active:
            message = (
                f"Reactivated member {member_id}, {current.full_name}. "
                "The record and its history were never removed."
            )
        else:
            message = (
                f"Deactivated member {member_id}, {current.full_name}. "
                "The record is kept and remains retrievable by id (D-06)."
            )
        return OperationResult(success=True, message=message, member=updated, changed=True)

    if connection is not None:
        return _work(connection)
    with connect() as owned:
        return _work(owned)


def can_be_placed_on_roster(
    member_id: int, *, connection: sqlite3.Connection | None = None
) -> OperationResult:
    """Return whether this member may be placed on a team roster.

    A deactivated member cannot be placed on a team (US-04 acceptance criterion 4). Placing
    players is WBS 4.4's job, so this is the check the roster code calls — the member side
    exposes the state, it does not write the roster.
    """

    def _work(connection: sqlite3.Connection) -> OperationResult:
        if not _is_identifier(member_id):
            return OperationResult(
                success=False,
                message=f"'{member_id}' is not a valid member id.",
                errors=("member_id must be a whole number",),
            )
        member = _fetch_member(connection, member_id)
        if member is None:
            return OperationResult(
                success=False,
                message=f"No member with member_id {member_id}.",
                errors=("unknown member_id",),
            )
        if not member.is_active:
            return OperationResult(
                success=False,
                message=(
                    f"Member {member_id}, {member.full_name}, is deactivated and cannot be "
                    "placed on a team roster. Reactivate the member first."
                ),
                member=member,
                errors=("member is deactivated",),
            )
        return OperationResult(
            success=True,
            message=f"Member {member_id}, {member.full_name}, may be placed on a team roster.",
            member=member,
        )

    if connection is not None:
        return _work(connection)
    with connect() as owned:
        return _work(owned)


# --- Small helpers ----------------------------------------------------------------------


def _is_identifier(value: Any) -> bool:
    """Return whether a value can be a member identifier (a positive whole number)."""
    if isinstance(value, bool):
        return False
    if isinstance(value, int):
        return value > 0
    if isinstance(value, str):
        return value.strip().isdigit() and int(value.strip()) > 0
    return False
